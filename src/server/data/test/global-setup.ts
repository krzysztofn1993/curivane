import { spawnSync } from "node:child_process";
import path from "node:path";
import postgres from "postgres";
import type { TestProject } from "vitest/node";

import { assertTestDatabase } from "./assert-test-database";

/**
 * Prepares `curivane_test` before any test runs:
 * 1. refuses to run unless the database name ends with `_test` (tests never touch the dev DB);
 * 2. creates the database on the same server if it does not exist;
 * 3. connects and checks `current_database()` ends with `_test`;
 * 4. applies `src/server/db/schema.ts` with `drizzle-kit push --force`;
 * 5. drops and recreates the isolation-test fixture table (see `user-data.test.ts`).
 *
 * If Postgres does not answer, the run fails (tests are not skipped).
 */
export default async function setup(project: TestProject) {
	const url = project.config.env.DATABASE_URL;
	if (!url) {
		throw new Error("Test setup: DATABASE_URL is not set in vitest.config.ts.");
	}

	const testUrl = new URL(url);
	const dbName = decodeURIComponent(testUrl.pathname.slice(1));
	if (!dbName.endsWith("_test")) {
		throw new Error(
			`Test setup: refusing to run against database "${dbName}"; its name must end with _test.`,
		);
	}

	const adminUrl = new URL(testUrl);
	adminUrl.pathname = "/postgres";

	const admin = postgres(adminUrl.toString(), {
		max: 1,
		connect_timeout: 5,
		onnotice: () => {},
	});
	try {
		try {
			await admin`select 1`;
		} catch (error) {
			throw new Error(
				`Test setup: Postgres at ${testUrl.host} does not answer. Uruchom ./start-database.sh (kontener curivane-postgres) i spróbuj ponownie.`,
				{ cause: error },
			);
		}
		const existing =
			await admin`select 1 from pg_database where datname = ${dbName}`;
		if (existing.length === 0) {
			await admin`create database ${admin(dbName)}`;
		}
	} finally {
		await admin.end();
	}

	const sql = postgres(testUrl.toString(), { max: 1, onnotice: () => {} });
	try {
		// Ask the server before drizzle-kit pushes anything.
		await assertTestDatabase(sql);

		// The child gets the test URL; drizzle.config.ts reads it through ~/env. drizzle-kit loads
		// `.env` with dotenv, which honours DOTENV_CONFIG_*; with DOTENV_CONFIG_OVERRIDE=true the
		// dev URL from `.env` would replace the test URL, so those variables are not passed on.
		const childEnv: NodeJS.ProcessEnv = {
			...process.env,
			DATABASE_URL: testUrl.toString(),
		};
		for (const key of Object.keys(childEnv)) {
			if (key.startsWith("DOTENV_CONFIG_")) delete childEnv[key];
		}
		const push = spawnSync(
			path.join(process.cwd(), "node_modules", ".bin", "drizzle-kit"),
			["push", "--force"],
			{ env: childEnv, encoding: "utf8" },
		);
		if (push.status !== 0) {
			throw new Error(
				`Test setup: drizzle-kit push failed for ${dbName}.\n${push.stdout}\n${push.stderr}`,
				{ cause: push.error },
			);
		}

		// Mirrors `ownedItems` in user-data.test.ts. No `curivane_` prefix, so drizzle-kit (filter
		// `curivane_*`) leaves it alone and it is not part of schema.ts. Dropped and created on every
		// run, so a change to this definition always reaches the existing test database.
		await sql`drop table if exists test_fixture_owned_item`;
		await sql`
			create table test_fixture_owned_item (
				id integer primary key generated by default as identity,
				"userId" varchar(255) not null references curivane_user(id) on delete cascade,
				name varchar(256) not null
			)
		`;
	} finally {
		await sql.end();
	}
}
